/* ------------------------------------------------------------- helpers */

/** Mirror a polygon across the vertical centre line. */
const mir = (pts, cx = 100) => pts.map(([x, y]) => [2 * cx - x, y]).reverse()

const ell = (cx, cy, rx, ry, rot = 0, n = 20) =>
  Array.from({ length: n }, (_, i) => {
    const a = (i / n) * Math.PI * 2
    const x = Math.cos(a) * rx
    const y = Math.sin(a) * ry
    return [cx + x * Math.cos(rot) - y * Math.sin(rot), cy + x * Math.sin(rot) + y * Math.cos(rot)]
  })

/** Evenly resample a polyline so tubes and segments have uniform spacing. */
function resample(line, step) {
  const out = [line[0]]
  let carry = 0
  for (let i = 1; i < line.length; i++) {
    const [ax, ay] = line[i - 1]
    const [bx, by] = line[i]
    const len = Math.hypot(bx - ax, by - ay)
    let t = step - carry
    while (t <= len) {
      out.push([ax + ((bx - ax) * t) / len, ay + ((by - ay) * t) / len])
      t += step
    }
    carry = len - (t - step)
  }
  return out
}

/** A thick stroke along a centre line, as one polygon. */
function tube(line, width) {
  const pts = resample(line, 4)
  const left = []
  const right = []
  pts.forEach((p, i) => {
    const a = pts[Math.max(0, i - 1)]
    const b = pts[Math.min(pts.length - 1, i + 1)]
    const dx = b[0] - a[0]
    const dy = b[1] - a[1]
    const m = Math.hypot(dx, dy) || 1
    const w = typeof width === 'function' ? width(i / (pts.length - 1)) : width
    left.push([p[0] - (dy / m) * w, p[1] + (dx / m) * w])
    right.push([p[0] + (dy / m) * w, p[1] - (dx / m) * w])
  })
  return [...left, ...right.reverse()]
}

const part = (pts, color, opts = {}) => ({ pts, color, ...opts })
const both = (pts, color, opts) => [part(pts, color, opts), part(mir(pts), color, opts)]
const eyes = (pts, color, glow, glowR = 8) => both(pts, color, { emit: true, glow, glowR, d: 2 })

